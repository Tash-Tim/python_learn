data = {
    (5000, 123456): ('Иванов', 'Василий'),
    (6000, 111111): ('Иванов', 'Петр'),
    (7000, 222222): ('Медведев', 'Алексей'),
    (8000, 333333): ('Алексеев', 'Георгий'),
    (9000, 444444): ('Георгиева', 'Мария')
}

inp_srl = int(input('Введите серию паспорта: '))
inp_num = int(input('Введите номер паспорта: '))
passport = (inp_srl, inp_num)

if passport in data:
    name, surname = data[passport]
    print(name, surname)
else:
    print('Такого человека в базе нет!')
